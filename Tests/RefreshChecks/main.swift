import Foundation

let now = Date(timeIntervalSince1970: 1_700_000_000)
var schedule = RefreshSchedule()
precondition(schedule.mayRefresh(at: now))
schedule.started(at: now)
precondition(!schedule.mayRefresh(at: now.addingTimeInterval(9)))
precondition(schedule.mayRefresh(at: now.addingTimeInterval(10)))
precondition(schedule.nextRefresh(popoverVisible: true) == now.addingTimeInterval(10))
precondition(schedule.nextRefresh(popoverVisible: false) == now.addingTimeInterval(60))
schedule.failed(rateLimited: false, at: now)
precondition(schedule.retryAt == now.addingTimeInterval(30))
precondition(schedule.nextRefresh(popoverVisible: false) == schedule.retryAt)
precondition(!schedule.mayRefresh(at: now.addingTimeInterval(29)))
precondition(schedule.mayRefresh(at: now.addingTimeInterval(30)))
schedule.failed(rateLimited: false, at: now)
precondition(schedule.retryAt == now.addingTimeInterval(60))
schedule.failed(rateLimited: false, at: now)
precondition(schedule.retryAt == now.addingTimeInterval(120))
schedule.failed(rateLimited: false, at: now)
precondition(schedule.retryAt == now.addingTimeInterval(300))
schedule.succeeded()
schedule.failed(rateLimited: true, at: now)
precondition(!schedule.mayRefresh(at: now.addingTimeInterval(299)))
precondition(schedule.nextRefresh(popoverVisible: true) == now.addingTimeInterval(300))
schedule.succeeded()
precondition(schedule.retryAt == nil)
schedule.failed(rateLimited: false, at: now)
precondition(schedule.retryAt == now.addingTimeInterval(30))
print("PASS: polling, request spacing, retry timing, and cooldown checks")
